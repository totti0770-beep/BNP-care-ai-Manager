export function getMockResponse(
  category: Category,
  userMessage: string
): { content: string; citation: { source: string; page: number } } {
  const categoryResponses = responses[category];
  const lowerMessage = userMessage.toLowerCase();

  for (const response of categoryResponses) {
    if (response.keywords[0] === "default") continue;
    if (response.keywords.some((kw) => lowerMessage.includes(kw))) {
      return { content: response.content, citation: response.citation };
    }
  }

  const defaultResponse = categoryResponses.find(
    (r) => r.keywords[0] === "default"
  )!;
  return {
    content: defaultResponse.content,
    citation: defaultResponse.citation,
  };
}
